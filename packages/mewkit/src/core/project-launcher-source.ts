// The committed launcher's source: a small Node script that finds this project's mewkit CLI
// (the Node package or the native binary) and runs it. Kept apart from the code that writes
// it because it is a template, not logic this module executes.

/** Which CLI installed the kit, and so which one the launcher tries first. */
export type LauncherPin = "node" | "native";

/**
 * The exit status of a launcher that found no CLI to run: the shell's "command not found".
 * A caller that must tell "no CLI here" (skip) from "the CLI ran and failed" (block) reads it.
 */
export const LAUNCHER_UNAVAILABLE_EXIT = 127;

/**
 * The launcher's own source, with the version and the installing CLI inlined. Generated
 * rather than shipped as a template so the pin cannot drift from the install that wrote it.
 *
 * The Rust binary's `init` writes the same file with `installedBy` = "native";
 * `crates/mewkit-adapters/src/claude_code/launcher.rs` carries that copy, and a test there
 * compares the two byte for byte.
 */
export function launcherSource(version: string, installedBy: LauncherPin = "node"): string {
	return `#!/usr/bin/env node
'use strict';
// Resolve this project's mewkit CLI and run it. Generated by the installer: VERSION is the
// CLI that installed this kit, INSTALLED_BY which kind it was (the Node package or the
// native binary). That kind is tried first and the other one second. A binary runs only
// when its --version banner names it and, for a native install, a compatible version.
// No branch downloads anything: a hook must not need a network, so an unresolvable CLI
// exits 127 with a next action.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const VERSION = ${JSON.stringify(version)};
const INSTALLED_BY = ${JSON.stringify(installedBy)};
const PROJECT_ROOT = path.resolve(__dirname, '..', '..');
const UNAVAILABLE = ${LAUNCHER_UNAVAILABLE_EXIT};
const BINARY_NAMES = ['mewkit', 'mk', 'mewkit-next'];

function usableFile(candidate) {
  if (!candidate || !path.isAbsolute(candidate)) return null;
  try {
    const real = fs.realpathSync(candidate);
    return fs.statSync(real).isFile() ? real : null;
  } catch {
    return null;
  }
}

function recordedEntry() {
  try {
    const file = path.join(os.homedir(), '.mewkit', 'cli', VERSION + '.json');
    const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
    return typeof parsed.entry === 'string' ? parsed.entry : null;
  } catch {
    return null;
  }
}

function nodeCli() {
  const candidates = [
    path.join(PROJECT_ROOT, 'node_modules', 'mewkit', 'dist', 'index.js'),
    path.join(PROJECT_ROOT, 'node_modules', '.bin', 'mewkit'),
  ];
  // Only a Node install recorded an entry for VERSION.
  if (INSTALLED_BY === 'node') candidates.push(recordedEntry());
  for (const candidate of candidates) {
    const real = usableFile(candidate);
    if (real) return { file: real, native: false };
  }
  return null;
}

function parseVersion(text) {
  const m = /^(\\d+)\\.(\\d+)\\.(\\d+)/.exec(text);
  return m ? [Number(m[1]), Number(m[2]), Number(m[3])] : null;
}

// Caret range against VERSION. A Node install's VERSION is the package's, which says
// nothing about the binary's, so there any binary will do.
function compatible(found) {
  if (INSTALLED_BY !== 'native') return true;
  const want = parseVersion(VERSION);
  if (!want || found[0] !== want[0]) return false;
  if (want[0] === 0 && found[1] !== want[1]) return false;
  for (let i = 0; i < 3; i++) {
    if (found[i] !== want[i]) return found[i] > want[i];
  }
  return true;
}

// \`mewkit 0.1.0\` (\`mewkit-next 0.1.0\` before the rename). The Node package prints a bare version, so its \`mewkit\` shim on
// PATH is never taken for the binary.
function binaryVersion(file) {
  const r = spawnSync(file, ['--version'], { encoding: 'utf8', timeout: 5000 });
  if (r.error || r.status !== 0) return null;
  const m = /^mewkit(?:-next)? (\\S+)\\s*$/.exec(String(r.stdout));
  return m ? parseVersion(m[1]) : null;
}

// This file is itself \`mewkit\` and its directory goes first on the agent's PATH, so it
// would otherwise probe and run itself, recursing until the timeout.
const SELF = usableFile(__filename);

function nativeCli() {
  const dirs = String(process.env.PATH || '').split(path.delimiter).filter(Boolean);
  if (process.env.MEWKIT_INSTALL_DIR) dirs.push(process.env.MEWKIT_INSTALL_DIR);
  dirs.push(path.join(os.homedir(), '.local', 'bin'));
  const ext = process.platform === 'win32' ? '.exe' : '';
  for (const dir of dirs) {
    for (const name of BINARY_NAMES) {
      const real = usableFile(path.join(dir, name + ext));
      const found = real && real !== SELF && binaryVersion(real);
      if (found && compatible(found)) return { file: real, native: true };
    }
  }
  return null;
}

const order = INSTALLED_BY === 'native' ? [nativeCli, nodeCli] : [nodeCli, nativeCli];
let cli = null;
for (const find of order) {
  cli = find();
  if (cli) break;
}
if (!cli) {
  process.stderr.write(
    'mewkit ' + VERSION + ' is not available to this project.\\n' +
      'Run \`mewkit doctor\` for the install state, or install the pinned version.\\n'
  );
  process.exit(UNAVAILABLE);
}

const args = process.argv.slice(2);
const result = cli.native
  ? spawnSync(cli.file, args, { stdio: 'inherit', cwd: process.cwd() })
  : spawnSync(process.execPath, [cli.file].concat(args), { stdio: 'inherit', cwd: process.cwd() });
process.exit(result.status === null ? 1 : result.status);
`;
}
