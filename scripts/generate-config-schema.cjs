#!/usr/bin/env node
'use strict';
// generate-config-schema.cjs — publish the project config's JSON Schema, and the
// list of environment names the config replaced.
//
// Both outputs are DERIVED, and for the same reason: a second hand-maintained
// copy of either one can disagree with the thing it describes, and the
// disagreement surfaces as an editor accepting a key the loader rejects, or a
// diagnostic naming a replacement key that no longer exists.
//
// The schema comes from the zod schema the loader validates with, by walking
// that schema's own definitions; the removed-name list comes from the
// classification table. A drift test asserts that re-running this is a no-op.
//
//   node scripts/generate-config-schema.cjs [--check]

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const OUT_REL = path.join('packages', 'mewkit', 'schemas', 'config-v1.json');
const REMOVED_REL = path.join('packages', 'mewkit', 'src', 'config', 'removed-env-names.ts');
const TABLE_REL = 'env-name-classification.json';
const SCHEMA_ID = 'https://meowkit.dev/schemas/config-v1.json';

/** Walk one zod definition into its JSON Schema equivalent. */
function toJsonSchema(schema) {
  const def = schema._def;
  switch (def.typeName) {
    case 'ZodOptional':
      return toJsonSchema(def.innerType);
    case 'ZodBoolean':
      return { type: 'boolean' };
    case 'ZodString':
      return { type: 'string' };
    case 'ZodNumber':
      return def.checks.some((c) => c.kind === 'int') ? { type: 'integer' } : { type: 'number' };
    case 'ZodEnum':
      return { type: 'string', enum: [...def.values] };
    case 'ZodObject': {
      const shape = def.shape();
      const properties = {};
      const required = [];
      for (const [key, value] of Object.entries(shape)) {
        properties[key] = toJsonSchema(value);
        if (value._def.typeName !== 'ZodOptional') required.push(key);
      }
      const out = { type: 'object', properties, additionalProperties: def.unknownKeys !== 'strict' };
      if (required.length > 0) out.required = required;
      return out;
    }
    default:
      throw new Error(`no JSON Schema mapping for ${def.typeName}`);
  }
}

function build() {
  // eslint-disable-next-line import/no-dynamic-require
  const { buildConfigSchema } = require(path.join(ROOT, 'packages', 'mewkit', 'dist', 'config', 'schema.js'));
  const { observerNames } = require(path.join(ROOT, 'packages', 'mewkit', 'dist', 'config', 'observer-names.js'));
  const names = observerNames(ROOT);
  if (names.length === 0) throw new Error('no observer names: .claude/hooks/handlers.json is missing or empty');
  const body = toJsonSchema(buildConfigSchema(names));
  return {
    $schema: 'https://json-schema.org/draft-07/schema#',
    $id: SCHEMA_ID,
    title: 'MeowKit project configuration',
    description:
      'The committed, human-owned project config at .meowkit/config.yaml. Generated from the loader\'s own schema; edit that, not this. There is no gates.* and no paths.* property at any scope, and unknown keys are errors rather than being ignored.',
    ...body,
  };
}

/**
 * The environment names the config replaced, as a module the CLI can compile in.
 *
 * A `toggle` row's key is what replaced it; a `drop` row has no replacement at
 * all. The exempt names are those whose class says `drop` for a reason other
 * than "a user should stop exporting this" — a module constant that matches the
 * scan regex, or a setting still honored by prose instead of by code.
 */
function buildRemoved() {
  const table = JSON.parse(fs.readFileSync(path.join(ROOT, TABLE_REL), 'utf8'));
  const exempt = new Set(Object.keys(table.removalExempt || {}).filter((k) => k !== 'comment'));
  const rows = table.names
    .filter((r) => (r.class === 'toggle' || r.class === 'drop') && !exempt.has(r.name))
    .map((r) => ({ name: r.name, replacement: r.key || r.replacedBy || "" }))
    .sort((a, b) => a.name.localeCompare(b.name));
  const entries = rows
    .map((r) => `\t{ name: "${r.name}", replacement: "${r.replacement}" },`)
    .join('\n');
  return [
    `// GENERATED by scripts/${path.basename(__filename)} from ${TABLE_REL} — do not edit.`,
    '//',
    '// Each name was readable from the environment in v2 and is not read anywhere',
    '// now. `replacement` is the config key that took it over, or empty when',
    '// nothing replaced it. An enforcement mode must never switch itself off in',
    '// silence, so a shell still exporting one of these is told about it.',
    '',
    'export interface RemovedEnvName {',
    '\treadonly name: string;',
    '\t/** The config key that replaced it, or "" when nothing did. */',
    '\treadonly replacement: string;',
    '}',
    '',
    'export const REMOVED_ENV_NAMES: readonly RemovedEnvName[] = [',
    entries,
    '];',
    '',
  ].join('\n');
}

/** Write or verify one derived file. Returns true when it is already current. */
function emit(rel, text, check) {
  const out = path.join(ROOT, rel);
  if (check) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (current === text) {
      process.stdout.write(`PASS: ${rel} is up to date\n`);
      return true;
    }
    process.stderr.write(`FAIL: ${rel} is stale — run node scripts/generate-config-schema.cjs\n`);
    return false;
  }
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, text);
  process.stdout.write(`wrote ${rel}\n`);
  return true;
}

function main() {
  const check = process.argv.includes('--check');
  const schemaOk = emit(OUT_REL, `${JSON.stringify(build(), null, '\t')}\n`, check);
  const removedOk = emit(REMOVED_REL, buildRemoved(), check);
  process.exit(schemaOk && removedOk ? 0 : 1);
}

main();
