#!/usr/bin/env node
'use strict';
// generate-cli-manual.cjs — one CLI reference for agents, generated from the catalogue.
//
// Verbs used to be learned from prose scattered across skills, which is how a skill came to
// instruct an agent to run a subcommand that had never existed. The surface is declared in
// exactly one place, so the manual is derived from that place and regenerating it is a
// no-op: it cannot describe a command that does not exist, and it cannot omit one that does.
//
//   node scripts/generate-cli-manual.cjs            # write the manual
//   node scripts/generate-cli-manual.cjs --check    # fail when it is out of date

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const MANUAL_REL = path.join('.claude', 'skills', 'help', 'references', 'cli.md');
const DIST = path.join(ROOT, 'packages', 'mewkit', 'dist', 'cli');

async function loadCatalogue() {
  const catalogue = await import(`file://${path.join(DIST, 'command-catalogue.js')}`);
  const flags = await import(`file://${path.join(DIST, 'flag-summary.js')}`);
  return { CLI_CATALOGUE: catalogue.CLI_CATALOGUE, flagLines: flags.flagLines };
}

function render({ CLI_CATALOGUE, flagLines }) {
  const lines = [
    '<!-- GENERATED by `node scripts/generate-cli-manual.cjs` — DO NOT EDIT BY HAND. -->',
    '',
    '# mewkit CLI reference',
    '',
    'Every command the CLI declares, with its subcommands and flags. Generated from the',
    'command catalogue, so a verb named here exists and a verb missing here does not.',
    '',
    'Exit codes: `0` ran and succeeded · `1` ran and failed · `2` the invocation was wrong',
    '(unknown command, unknown subcommand, or a missing subcommand on a command that requires',
    'one). `mewkit <command> <subcommand> --help` prints that subcommand\'s usage and runs nothing.',
    '',
  ];

  for (const command of CLI_CATALOGUE.commands) {
    // `## mewkit <name>` so a command entry is countable and distinct from the
    // global-flag section at the end.
    lines.push(`## mewkit ${command.name}`, '', command.summary, '');
    lines.push(`Usage: \`mewkit ${command.usage ?? command.name}\``, '');
    const subs = command.subcommands ?? [];
    if (subs.length > 0) {
      lines.push(command.requiresSubcommand ? 'Subcommands (one is required):' : 'Subcommands:', '');
      for (const sub of subs) {
        const usage = command.subcommandUsage?.[sub];
        lines.push(`- \`${sub}\`${usage ? ` — \`mewkit ${usage}\`` : ''}`);
      }
      lines.push('');
    }
    const flags = flagLines(CLI_CATALOGUE, command.name);
    if (flags.length > 0) {
      lines.push('Flags:', '', '```text', ...flags, '```', '');
    }
  }

  const globals = flagLines(
    { ...CLI_CATALOGUE, flags: CLI_CATALOGUE.flags.filter((f) => f.commands.length === 0).map((f) => ({ ...f, commands: ['*'] })) },
    '*'
  );
  if (globals.length > 0) lines.push('## Global flags', '', '```text', ...globals, '```', '');

  return `${lines.join('\n').replace(/\n+$/, '')}\n`;
}

async function main(argv) {
  let loaded;
  try {
    loaded = await loadCatalogue();
  } catch {
    process.stderr.write('packages/mewkit/dist is not built; run `npm run build` first\n');
    return 1;
  }
  const target = path.join(ROOT, MANUAL_REL);
  const rendered = render(loaded);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;

  if (argv.includes('--check')) {
    if (current === rendered) {
      process.stdout.write(`PASS: ${MANUAL_REL} matches the command catalogue\n`);
      return 0;
    }
    process.stdout.write(
      `FAIL: ${MANUAL_REL} is ${current === null ? 'missing' : 'stale'}.\n` +
        'The CLI surface changed without the manual being regenerated.\n' +
        'Fix: node scripts/generate-cli-manual.cjs\n'
    );
    return 1;
  }

  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, rendered, 'utf8');
  process.stdout.write(`${current === rendered ? 'unchanged' : 'wrote'} ${MANUAL_REL}\n`);
  return 0;
}

module.exports = { render, loadCatalogue, MANUAL_REL };

if (require.main === module) {
  main(process.argv.slice(2)).then((code) => process.exit(code));
}
