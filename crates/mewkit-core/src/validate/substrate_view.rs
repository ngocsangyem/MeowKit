//! The committed substrate view: generated, never hand-edited.
//!
//! Stable ordering is what keeps the regenerate-and-diff drift check clean, so
//! the renderer lives beside the aggregate it renders and nothing else writes
//! this markdown.
use super::substrate::{Coverage, SubstrateAggregate};

/// The deterministic markdown view — generated, never hand-edited. Stable
/// ordering is what keeps the regenerate-and-diff drift check clean.
pub fn render_substrate_view(aggregate: &SubstrateAggregate) -> String {
    let covered = aggregate
        .rows
        .iter()
        .filter(|row| row.coverage == Coverage::Covered)
        .count();
    let missing: Vec<&str> = aggregate
        .rows
        .iter()
        .filter(|row| row.coverage == Coverage::Missing)
        .map(|row| row.label)
        .collect();
    let mut lines = vec![
        "<!-- GENERATED by `node scripts/harness-inventory.cjs --substrate --emit` — DO NOT EDIT BY HAND. -->".to_string(),
        "<!-- Regenerate after tagging; `mewkit validate` fails if this drifts from the registry. -->".to_string(),
        String::new(),
        "# Harness Responsibility Substrate".to_string(),
        String::new(),
        "Coverage of each vendor-neutral substrate responsibility, generated from the harness registry \
         + artifact frontmatter. Eleven core values are the Runtime-Substrate taxonomy (repo-harness \
         synthesis, Runtime-Substrate-rooted); `Gate enforcement` is the kit-specific addition.".to_string(),
        String::new(),
        "| Responsibility | Coverage | Tagged | Active | Examples |".to_string(),
        "| -------------- | -------- | -----: | -----: | -------- |".to_string(),
    ];
    for row in &aggregate.rows {
        let label = if row.core {
            row.label.to_string()
        } else {
            format!("{} *(kit)*", row.label)
        };
        let examples = if row.examples.is_empty() {
            "—".to_string()
        } else {
            row.examples.join(", ")
        };
        lines.push(format!(
            "| {label} | {} | {} | {} | {examples} |",
            row.coverage.icon(),
            row.count,
            row.active
        ));
    }
    lines.push(String::new());
    lines.push(format!(
        "**Coverage:** {covered}/{} responsibilities have active artifacts.{}",
        aggregate.rows.len(),
        if missing.is_empty() {
            String::new()
        } else {
            format!(" Missing: {}.", missing.join(", "))
        }
    ));
    lines.push(format!(
        "**Untagged:** {} registry + {} frontmatter artifacts carry no responsibility \
         (frontmatter is tag-on-touch; registry should be 100%).",
        aggregate.untagged_registry.len(),
        aggregate.untagged_frontmatter.len()
    ));
    lines.join("\n")
}
