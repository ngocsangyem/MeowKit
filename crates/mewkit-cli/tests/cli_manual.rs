//! The agent-facing CLI reference stays in step with the clap definition.
//!
//! Skills learn verbs from one generated manual rather than from scattered prose, so it
//! is derived from the command definition: it cannot describe a command that does not
//! exist or omit one that does. `MEWKIT_BLESS=1 cargo test -p mewkit-cli --test
//! cli_manual` rewrites it.

mod cli_surface;

use std::fmt::Write as _;
use std::path::PathBuf;

use cli_surface::Node;

fn manual_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../.claude/skills/help/references/cli.md")
}

/// Heading depth grows with nesting but stops at 4 so deep paths stay readable.
fn render_node(out: &mut String, node: &Node) {
    let level = "#".repeat((node.path.len() + 1).min(4));
    let help = node.help.replace("mewkit-next", "mewkit");
    let _ = write!(
        out,
        "{level} mewkit {}\n\n```text\n{}\n```\n\n",
        node.path.join(" "),
        help.trim_end()
    );
    for child in &node.children {
        render_node(out, child);
    }
}

fn render() -> String {
    let mut out = String::from(
        "<!-- GENERATED by `MEWKIT_BLESS=1 cargo test -p mewkit-cli --test cli_manual` — DO NOT EDIT BY HAND. -->\n\n\
# mewkit CLI reference\n\n\
Every command the CLI declares, with its subcommands and flags, as clap prints them.\n\
Generated from the command definition, so a verb named here exists and a verb missing\n\
here does not.\n\n\
Exit codes: `0` ran and succeeded · `1` ran and failed · `2` the invocation was wrong\n\
(unknown command, unknown subcommand, or a missing subcommand on a command that requires\n\
one). `mewkit <command> <subcommand> --help` prints that subcommand's usage and runs nothing.\n\n",
    );
    for verb in cli_surface::verbs() {
        render_node(&mut out, &verb);
    }
    format!("{}\n", out.trim_end())
}

#[test]
fn manual_matches_clap_definition() {
    let rendered = render();
    let path = manual_path();
    if std::env::var("MEWKIT_BLESS").is_ok_and(|v| v == "1") {
        std::fs::write(&path, &rendered).expect("write cli.md");
        return;
    }
    // Compare modulo CRLF so a Windows checkout with autocrlf does not fail spuriously.
    let current = std::fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    // Name the first differing line so a failure on a platform nobody can bless from
    // locally is diagnosable from the CI log alone.
    let first_diff = current
        .lines()
        .zip(rendered.lines())
        .enumerate()
        .find(|(_, (a, b))| a != b)
        .map(|(i, (a, b))| format!("line {}:\n  committed: {a}\n  rendered:  {b}", i + 1))
        .unwrap_or_else(|| "the files differ in length".to_string());
    assert!(
        current == rendered,
        ".claude/skills/help/references/cli.md is stale or missing: the CLI surface changed \
         without the manual being regenerated.\n{first_diff}\nFix: MEWKIT_BLESS=1 cargo test \
         -p mewkit-cli --test cli_manual"
    );
}
